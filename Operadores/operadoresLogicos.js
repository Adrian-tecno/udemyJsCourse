// * Operadores lógicos:
let a = true;
let b = false;
console.log(a);
console.log(b);

// ? Operador lógico && (and o y)
// Regresa verdadero si ambos operandos son verdaderos.
console.log(`${a} && ${b} => ${a && b} `);

// ? Operador lógico || (or u o)
// Regresa verdadero si cualquiera de los valores es verdadero
console.log(`${a} || ${b} => ${a || b}`);

// ? Operador ! (NOT o NO)
// Invierte el valor original, true => false o false => true.
console.log(`${a} => ${!a}`);
